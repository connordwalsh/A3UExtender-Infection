def collect(log_path: Path, repo: Path, expected_dependencies: bool, suite: str = "full") -> dict:
    raw = log_path.read_bytes()
    records, malformed, errors, warnings = [], [], [], []
    for number, line in enumerate(raw.decode("utf-8", errors="replace").splitlines(), 1):
        if re.search(r"Error(?::|\s+(?:in expression|Undefined|Missing|Generic|Type))", line) or re.search(
            r"Attempt to override final function - a3[ai]_", line, re.IGNORECASE
        ):
            errors.append(number)
        if any(text in line for text in ("Warning Message:", "not found or empty", "item count not multiple", "Attempt to override final function", "Server: Object", "Invalid convex component", "A null object passed as a target")):
            # Preserve known dependency/engine warnings separately from SQF failures.
            warnings.append({"line": number, "message": line.split(" ", 1)[-1]})
        if "[INFECTION_TEMPLATE] " not in line:
            continue
        payload = line.split("[INFECTION_TEMPLATE] ", 1)[1].strip()
        if payload.endswith('"'):
            payload = payload[:-1].replace('""', '"')
        try:
            record = parse_array(payload)
            shapes = {"start": 7, "check": 4, "spawn": 4, "complete": 4}
            if not record or len(record) != shapes.get(record[0], -1):
                raise ValueError("Unexpected record shape")
            records.append(record)
        except (ValueError, json.JSONDecodeError):
            malformed.append(number)
    by_kind = {k: [r for r in records if r[0] == k] for k in ("start", "check", "spawn", "complete")}
    starts, finishes = by_kind["start"], by_kind["complete"]
    complete = len(starts) == len(finishes) == 1
    expected_checks = COMMON | ({
        "active_only_for_occupants", "role_count", "generated_groups_resolve", "prepared_basic_classes_only",
        "assets_resolve", "conventional_pools_empty", "cleanup",
    } | GARRISON_CHECKS | COMBAT_CHECKS | BUDGET_CHECKS | SPAWN_CHECKS | SITE_CHECKS | CONTROL_CHECKS | CITY_CHECKS | ADMIN_CHECKS | REINFORCEMENT_CHECKS | ROAMING_CHECKS | COUNTERATTACK_CHECKS | TACTICAL_CHECKS | MAJOR_CHECKS | CATALOG_POLICY_CHECKS | CLEARANCE_CHECKS | LIQUIDATION_CHECKS | LIQUIDATION_CONTROLLER_CHECKS | LIQUIDATION_DISPATCH_CHECKS | INTERCEPTION_CHECKS | INTERCEPTION_FORMATION_CHECKS | INTERCEPTION_TASK_CHECKS | INTERCEPTION_STORAGE_CHECKS | INTERCEPTION_ADOPTION_CHECKS | ADMINISTRATION_EXTRA_CHECKS | INTERCEPTION_AFTERMATH_CHECKS | INTERCEPTION_DISPATCH_CHECKS | DELIVERY_CHECKS | EXTRACTION_LEDGER_CHECKS | AID_LEDGER_CHECKS | AID_TASK_CHECKS | ELIMINATION_LEDGER_CHECKS | ELIMINATION_SCENE_CHECKS | ELIMINATION_TASK_CHECKS | ELIMINATION_DISPATCH_CHECKS | EXTRACTION_SCENE_CHECKS | SUPPLY_TRUCK_CHECKS | ABANDONED_VEHICLE_CHECKS | SUPPLY_TASK_CHECKS | SUPPLY_DISPATCH_CHECKS | BACKGROUND_CONVOY_CHECKS | {"spawn_" + name for name in EXPECTED_ROLES} if expected_dependencies else {"both_required_patches_absent"})
    expected_roles = EXPECTED_ROLES if expected_dependencies else []
    if suite in ("administration", "reinforcements", "roaming", "counterattacks", "towns", "tactical", "major", "catalogpolicy", "clearance", "liquidation", "liquidationcontroller", "liquidationdispatch", "interception", "interceptionformation", "formationregression", "interceptiontask", "interceptionstorage", "interceptionarrivals", "administrationextras", "interceptionaftermath", "interceptiondispatch", "delivery", "extractionledger", "aidledger", "aidtask", "eliminationledger", "eliminationscenes", "eliminationtask", "eliminationdispatch", "extractionscenes", "supplytrucks", "abandonedvehicles", "abandonedtowns", "reduxparking", "supplytask", "supplydispatch", "backgroundconvoys"):
        if not expected_dependencies:
            raise ValueError("Focused suites require dependencies")
        focused_checks = {"administration": ADMIN_CHECKS, "reinforcements": REINFORCEMENT_CHECKS, "roaming": ROAMING_CHECKS,
                          "counterattacks": COUNTERATTACK_CHECKS, "towns": CITY_CHECKS, "tactical": TACTICAL_CHECKS, "major": MAJOR_CHECKS,
                          "catalogpolicy": CATALOG_POLICY_CHECKS, "clearance": CLEARANCE_CHECKS, "liquidation": LIQUIDATION_CHECKS, "liquidationcontroller": LIQUIDATION_CONTROLLER_CHECKS, "liquidationdispatch": LIQUIDATION_DISPATCH_CHECKS, "interception": BUDGET_CHECKS | INTERCEPTION_CHECKS, "interceptionformation": INTERCEPTION_FORMATION_CHECKS, "interceptiontask": INTERCEPTION_TASK_CHECKS, "interceptionstorage": INTERCEPTION_STORAGE_CHECKS, "interceptionarrivals": INTERCEPTION_STORAGE_CHECKS | INTERCEPTION_ADOPTION_CHECKS, "administrationextras": ADMINISTRATION_EXTRA_CHECKS, "interceptionaftermath": INTERCEPTION_AFTERMATH_CHECKS, "interceptiondispatch": INTERCEPTION_DISPATCH_CHECKS, "delivery": DELIVERY_CHECKS, "extractionledger": EXTRACTION_LEDGER_CHECKS, "aidledger": AID_LEDGER_CHECKS, "aidtask": AID_TASK_CHECKS, "eliminationledger": ELIMINATION_LEDGER_CHECKS, "eliminationscenes": ELIMINATION_SCENE_CHECKS, "eliminationtask": ELIMINATION_TASK_CHECKS, "eliminationdispatch": ELIMINATION_DISPATCH_CHECKS, "extractionscenes": EXTRACTION_SCENE_CHECKS, "supplytrucks": SUPPLY_TRUCK_CHECKS, "abandonedvehicles": ABANDONED_VEHICLE_CHECKS, "abandonedtowns": ABANDONED_TOWN_CHECKS, "reduxparking": REDUX_PARKING_CHECKS, "supplytask": SUPPLY_TASK_CHECKS, "supplydispatch": SUPPLY_DISPATCH_CHECKS, "formationregression": LIQUIDATION_CHECKS | INTERCEPTION_FORMATION_CHECKS, "backgroundconvoys": BACKGROUND_CONVOY_CHECKS}
        expected_checks = COMMON | {"active_only_for_occupants"} | focused_checks[suite]
        expected_roles = []
    checks = {
        "one_start_and_completion": complete,
        "record_schema_valid": not malformed,
        "dedicated_expected_mode": len(starts) == 1 and starts[0][2:] == [({"abandonedtowns": "Altis", "reduxparking": "chernarusredux"}.get(suite, "VR")), True, 2, expected_dependencies, suite],
        "all_expected_checks_once": Counter(r[1] for r in by_kind["check"]) == Counter(expected_checks),
        "all_runtime_checks_pass": bool(by_kind["check"]) and all(r[2] is True for r in by_kind["check"]),
        "completion_matches_checks": complete and finishes[0][1:] == [len(expected_checks), [], len(expected_roles)],
        "all_expected_roles_once": Counter(r[1] for r in by_kind["spawn"]) == Counter(expected_roles),
        "all_role_spawns_pass": all(r[3] is True for r in by_kind["spawn"]),
        "no_engine_or_sqf_error_records": not errors,
    }
    fixture_files = sorted((repo / "tests/arma/infection_probe/template.VR").glob("*"))
    fixture_files += sorted((repo / "tests/arma/infection_probe/contracts-addon").glob("*")) if expected_dependencies else []
    source_files = sorted((repo / "Infection").rglob("*"))
    return {
        "schema_version": 1,
        "scope": "Isolated dedicated contracts, suite=" + suite + "; no full campaign, player credit, client rescue, ACE, HC transfer or JIP acceptance",
        "suite": suite,
        "expected_dependencies_present": expected_dependencies,
        "status": "passed" if all(checks.values()) else ("failed" if complete else "incomplete"),
        "collected_at_utc": datetime.now(timezone.utc).isoformat(),
        "source_log": log_path.name,
        "source_log_sha256_at_collection": hashlib.sha256(raw).hexdigest(),
        "source_sha256_at_collection": {p.relative_to(repo).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                                        for p in fixture_files + source_files if p.is_file()},
        "checks": checks,
        "malformed_record_lines": malformed,
        "error_lines": errors,
        "warnings_for_review": warnings,
        "runtime_checks": [{"name": r[1], "passed": r[2], "detail": r[3]} for r in by_kind["check"]],
        "spawn_records": by_kind["spawn"],
        "completion": finishes[0][1:] if len(finishes) == 1 else None,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("log", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--dependencies", choices=("present", "absent"), required=True)
    parser.add_argument("--suite", choices=("full", "administration", "reinforcements", "roaming", "counterattacks", "towns", "tactical", "major", "catalogpolicy", "clearance", "liquidation", "liquidationcontroller", "liquidationdispatch", "interception", "interceptionformation", "formationregression", "interceptiontask", "interceptionstorage", "interceptionarrivals", "administrationextras", "interceptionaftermath", "interceptiondispatch", "delivery", "extractionledger", "aidledger", "aidtask", "eliminationledger", "eliminationscenes", "eliminationtask", "eliminationdispatch", "extractionscenes", "supplytrucks", "abandonedvehicles", "abandonedtowns", "reduxparking", "supplytask", "supplydispatch", "backgroundconvoys"), default="full")
    args = parser.parse_args()
    report = collect(args.log, Path(__file__).resolve().parents[2], args.dependencies == "present", args.suite)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"status": report["status"], "checks": report["checks"]}))
    return 0 if report["status"] == "passed" else 2


